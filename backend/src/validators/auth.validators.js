import { z } from "zod";

// Дозволені символи в імені: літери (будь-якої мови), цифри, пробіл,
// апостроф і дефіс — і ім'я обов'язково починається й закінчується
// літерою/цифрою (щоб не можна було зареєструвати " Юліана" чи
// "Юліана-" з зайвим знаком по краях).
const NAME_REGEX = /^[\p{L}\p{N}][\p{L}\p{N} '’-]*[\p{L}\p{N}]$/u;

// trim() прибирає пробіли з країв, а replace() схлопує будь-яку
// послідовність пробілів/табів усередині в один пробіл. Без цього
// "Юліана" й "Юліана  " (з подвійним пробілом) виглядали б різними
// іменами, хоча для ока — та сама людина, і можна було б обійти
// перевірку на унікальність.
const cleanName = z
  .string({ required_error: "Потрібне ім'я" })
  .trim()
  .transform((val) => val.replace(/\s+/g, " "));

// Винесено окремо (не лише всередині registerSchema), щоб ті самі правила
// імені використовував і users.validators.js#updateProfileSchema —
// перейменування акаунту в профілі мусить підкорятись тим самим обмеженням,
// що й реєстрація.
export const nameSchema = cleanName
  .refine((val) => val.length >= 2, "Ім'я має містити щонайменше 2 символи")
  .refine((val) => val.length <= 40, "Ім'я задовге (максимум 40 символів)")
  .refine(
    (val) => NAME_REGEX.test(val),
    "Ім'я може містити лише літери, цифри, пробіли, апостроф і дефіс"
  );

export const registerSchema = z.object({
  name: nameSchema,
  password: z
    .string({ required_error: "Потрібен пароль" })
    .min(6, "Пароль має містити мінімум 6 символів")
    .max(72, "Пароль задовгий"),
});

export const loginSchema = z.object({
  // При вході свідомо не женемо ім'я крізь NAME_REGEX — досить того, що
  // воно збігається (без урахування регістру) з якимось зареєстрованим;
  // якщо ні, User.findOne просто нічого не знайде і піде звичайна
  // помилка "Невірне ім'я або пароль".
  name: cleanName.refine((val) => val.length >= 1, "Потрібне ім'я"),
  password: z.string({ required_error: "Потрібен пароль" }).min(1, "Потрібен пароль"),
});
